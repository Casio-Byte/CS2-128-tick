"""Turn work/patches.json into src/patches.h for the Windows app, and write docs/patched_sites.txt."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
WORK = os.environ.get("CS2_WORK", os.path.join(ROOT, "work"))
P = json.load(open(os.path.join(WORK, "patches.json")))
o = ["/* generated by tools/gen_header.py - do not edit */",
     "typedef struct { unsigned char tier; unsigned int off; unsigned char len; unsigned char oldb[8]; unsigned char newb[8]; } PatchEntry;",
     "typedef struct { const char *name; const char *rel; const char *sha; const PatchEntry *p; int n; } PatchFile;"]
names = []
def arr(b): return "{" + ",".join(str(x) for x in b.ljust(8, b"\0")) + "}"
for i, (fn, inf) in enumerate(P["files"].items()):
    rows = []
    for p in inf["patches"]:
        ob, nb = bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        rows.append(f"{{{1 if p['tier'] == 'aggressive' else 0},{p['off']}u,{len(ob)},{arr(ob)},{arr(nb)}}}")
    o.append(f"static const PatchEntry P{i}[] = {{\n" + ",\n".join(rows) + "\n};")
    rel = inf["path"].replace("/", "\\\\")
    names.append(f'{{"{fn}","{rel}","{inf["sha256"]}",P{i},{len(rows)}}}')
o.append("static const PatchFile FILES[] = {" + ",".join(names) + "};\n#define NFILES " + str(len(names)))
open(os.path.join(ROOT, "src", "patches.h"), "w").write("\n".join(o))
with open(os.path.join(ROOT, "docs", "patched_sites.txt"), "w") as f:
    f.write("Every edited site (file offsets are for the exact build below only)\n")
    for fn, inf in P["files"].items():
        f.write(f"\n== {fn}  sha256 {inf['sha256']}\n")
        for p in inf["patches"]:
            f.write(f"{p['tier']:10} file+{p['off']:#09x}  {p['what']}\n")
print("wrote src/patches.h and docs/patched_sites.txt")
