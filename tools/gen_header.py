"""Turn work/patches.json into src/patches.h for the Windows app, and write docs/patched_sites.txt."""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
import sys
# Usage: gen_header.py [work_dir_newest work_dir_older ...]  (default: ./work). Every build listed is supported.
WORKS = sys.argv[1:] or [os.environ.get("CS2_WORK", os.path.join(ROOT, "work"))]
BUILDS = [json.load(open(os.path.join(w, "patches.json"))) for w in WORKS]
o = ["/* generated by tools/gen_header.py - do not edit */",
     "enum { K_FIXED = 0, K_F_INV, K_F_RATE, K_D_INV, K_D_RATE };   /* rate-dependent entries are computed at patch time */",
     "typedef struct { unsigned char tier; unsigned char kind; unsigned int off; unsigned char len; unsigned char oldb[8]; unsigned char newb[8]; } PatchEntry;",
     "typedef struct { const char *name; const char *rel; const char *sha; const PatchEntry *p; int n; int build; } PatchFile;   /* build: 0 = newest */"]
names = []
def arr(b): return "{" + ",".join(str(x) for x in b.ljust(8, b"\0")) + "}"
KIND = {'fixed': 'K_FIXED', 'f_inv': 'K_F_INV', 'f_rate': 'K_F_RATE', 'd_inv': 'K_D_INV', 'd_rate': 'K_D_RATE'}
idx = 0; newest = []
for bi, P in enumerate(BUILDS):
    for fn, inf in P["files"].items():
        rows = []
        for p in inf["patches"]:
            ob, nb = bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
            rows.append(f"{{{1 if p['tier'] == 'aggressive' else 0},{KIND[p['kind']]},{p['off']}u,{len(ob)},{arr(ob)},{arr(nb)}}}")
        o.append(f"static const PatchEntry P{idx}[] = {{\n" + ",\n".join(rows) + "\n};")
        rel = inf["path"].replace("/", "\\\\")
        ent = f'{{"{fn}","{rel}","{inf["sha256"]}",P{idx},{len(rows)},{bi}}}'
        names.append(ent)
        if bi == 0: newest.append(ent)
        idx += 1
o.append("/* newest build, one entry per DLL: names, paths and edit counts shown in the app */")
o.append("static const PatchFile FILES[] = {" + ",".join(newest) + "};\n#define NFILES " + str(len(newest)))
o.append("/* every supported build of every DLL */")
o.append("static const PatchFile ALL_BUILDS[] = {" + ",".join(names) + "};\n#define NALL " + str(len(names)))
open(os.path.join(ROOT, "src", "patches.h"), "w").write("\n".join(o))
with open(os.path.join(ROOT, "docs", "patched_sites.txt"), "w") as f:
  f.write("Every edited site, per supported build (file offsets only apply to the build with that SHA-256)\n")
  for P in BUILDS:
    for fn, inf in P["files"].items():
        f.write(f"\n== {fn}  sha256 {inf['sha256']}\n")
        for p in inf["patches"]:
            what = p['what'] if p['kind'] == 'fixed' else p['what'] + "   (value = 1/rate or rate, set at patch time)"
            f.write(f"{p['tier']:10} file+{p['off']:#09x}  {what}\n")
print("wrote src/patches.h and docs/patched_sites.txt")
