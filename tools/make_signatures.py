"""
Build per-site fingerprints from a reference build so the app can carry the patch over to a new CS2 build itself.

For every patched instruction we store a byte window around it (up to PRE bytes before, POST after) plus a mask.
Masked bytes are the ones that move between builds: RIP-relative displacements, rel32 call/jmp/jcc targets,
and the site's own displacement / immediate. At runtime the app looks for each fingerprint only at places in the
new DLL that read a 1/64 or 64.0 constant (or hold a 1/64 immediate), so matching is fast and specific.

Usage:  python tools/make_signatures.py <work_dir>      (reference build: needs patches.json, <dll>.json, the DLLs)
Writes: src/signatures.h
"""
import os, sys, json, struct, pefile
from capstone import Cs, CS_ARCH_X86, CS_MODE_64

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
WORK = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "work")
# --uncovered a,b,c : 1/64 reads in the reference build not covered by a site (run tools/port_check on the
# reference build to get them). The app tolerates a few more than this on a new build.
UNCOV = [int(x) for x in (sys.argv[sys.argv.index("--uncovered") + 1].split(",") if "--uncovered" in sys.argv else ["0", "0", "0"])]
PRE, POST = 48, 48
FILES = ["engine2.dll", "server.dll", "client.dll"]
SRC = {"f1/64": 1, "f64": 2, "d1/64": 3, "d64": 4, "imm f1/64": 5}
DST = {"f1/128": "K_F_INV", "f128": "K_F_RATE", "d1/128": "K_D_INV", "d128": "K_D_RATE"}

P = json.load(open(os.path.join(WORK, "patches.json")))
md = Cs(CS_ARCH_X86, CS_MODE_64)
sites, blob, mask = [], bytearray(), bytearray()
groups = {}

def rel32_mask(ins):
    """byte offsets (within the instruction) that hold build-dependent addresses"""
    b = bytes(ins.bytes); offs = []
    if "rip" in ins.op_str:
        import re
        m = re.search(r"rip ([+-]) (0x[0-9a-f]+|\d+)\]", ins.op_str)
        if m:
            d = int(m.group(2), 0) * (1 if m.group(1) == "+" else -1)
            k = b.find(struct.pack("<i", d))
            if k >= 0: offs += range(k, k + 4)
    if b[0] in (0xE8, 0xE9) and len(b) == 5: offs += range(1, 5)
    if len(b) >= 6 and b[0] == 0x0F and 0x80 <= b[1] <= 0x8F: offs += range(2, 6)
    return offs

for fi, fn in enumerate(FILES):
    info = P["files"][fn]
    hits = {h["addr"]: h for h in json.load(open(os.path.join(WORK, fn[:-4] + ".json")))["hits"]}
    pe = pefile.PE(os.path.join(WORK, fn), fast_load=True)
    crit_engine = set()
    for p in info["patches"]:
        if p["what"].startswith("const slot"): continue
        rva = int(p["what"].split("@rva ")[1].split()[0], 16)
        h = hits[rva]
        size = h["size"]
        if h["kind"].startswith("imm"):
            off, dst = size - 4, "K_F_INV"
        else:
            off, dst = h["disp_off"], DST[p["what"].split("-> ")[-1]]
        start = rva; func = h["func"]
        pre = min(PRE, start - func)
        lo, hi = start - pre, start + size + POST
        win = bytearray(pe.get_data(lo, hi - lo)); msk = bytearray(b"\x01" * len(win))
        # decode from the function start through the window and mask moving bytes
        for ins in md.disasm(pe.get_data(func, hi + 16 - func), func):
            if ins.address >= hi: break
            for o in rel32_mask(ins):
                a = ins.address + o
                if lo <= a < hi: msk[a - lo] = 0
        for o in range(off, off + 4): msk[start - lo + o] = 0          # the site's own disp / immediate
        critical = int(h.get("cls", "") == "tick:getter" or (fn == "engine2.dll" and (h["kind"].startswith("imm") or "ucomiss" in h["mn"] or h["kind"] == "d64")))
        tier = 1 if p["tier"] == "aggressive" else 0
        # identical code (same masked window + same patch) is grouped: every copy gets the same patch
        key = (fi, tier, SRC[h["kind"]], dst, size, off, pre, bytes(w if m else 0 for w, m in zip(win, msk)), bytes(msk))
        if key in groups:
            g = groups[key]; g[1] += 1; g[0][4] = g[0][4] or critical
            continue
        rec = [fi, tier, SRC[h["kind"]], dst, critical, size, off, size - off - 4, pre, len(win), len(blob), 1, rva]
        groups[key] = [rec, 1]
        sites.append(rec)
        blob += win; mask += msk

with open(os.path.join(ROOT, "src", "signatures.h"), "w") as f:
    f.write("/* generated by tools/make_signatures.py from reference build %s - do not edit */\n" % P["files"]["engine2.dll"]["sha256"][:16])
    f.write("enum { S_F_INV64 = 1, S_F_RATE64, S_D_INV64, S_D_RATE64, S_IMM_F_INV64 };\n")
    for rec in sites: rec[11] = groups[next(k for k, g in groups.items() if g[0] is rec)][1]
    f.write("/* count = how many identical copies of this code the reference build has */\n")
    f.write("typedef struct { unsigned char file, tier, src, dst, critical, size, off, extra, pre; unsigned short len; unsigned int at; unsigned short count; unsigned int ref; } SigSite;   /* ref = RVA in the reference build (diagnostics) */\n")
    f.write("static const SigSite SIGS[] = {\n" + ",\n".join("{%d,%d,%d,%s,%d,%d,%d,%d,%d,%d,%d,%d,0x%x}" % tuple(s) for s in sites) + "\n};\n")
    f.write("#define NSITES_TOTAL %d\n" % sum(r[11] for r in sites))
    f.write("#define PORT_BASE_UNCOVERED0 %d\n#define PORT_BASE_UNCOVERED1 %d\n#define PORT_BASE_UNCOVERED2 %d\n" % tuple(UNCOV))
    f.write("#define NSIGS %d\n" % len(sites))
    def carr(name, data):
        f.write("static const unsigned char %s[%d] = {\n" % (name, len(data)))
        for i in range(0, len(data), 40): f.write(",".join(str(x) for x in data[i:i + 40]) + ",\n")
        f.write("};\n")
    carr("SIG_BYTES", blob); carr("SIG_MASK", mask)
print("wrote src/signatures.h:", len(sites), "sites,", len(blob), "bytes")
