"""Generate the C site table (sites_1420.h) from the plans."""
import os, json, struct, bisect, re, hashlib, pefile

KIND = {'f_64': 0, 'f_inv': 1, 'd_64': 2, 'd_inv': 3}
# engine2 0x61459: "if (window_cmds > 256) { warn every tick; window_cmds = 256 }".
# At 128/256 tick the window (cvar * rate) is always > 256, so the warning floods the console.
# 0x6145b: jmp 0x6149e (EB 41) -> keep the clamp to 256, skip the message.
RAW = {'engine2': [(0x6145b, bytes.fromhex('eb41'), 'raw: silence cl_tickpacket_recvmargin_window spam, keep the 256 clamp')]}
ORIG = {'f_64': struct.pack('<f', 64.0), 'f_inv': struct.pack('<f', 1/64)}

def pick_pad(pe, d, need, align, avoid, margin=1):
    t = pe.sections[0]
    va, raw = t.VirtualAddress, t.PointerToRawData
    code = d[raw:raw + t.Misc_VirtualSize]
    pd = [s for s in pe.sections if s.Name.startswith(b'.pdata')][0]
    fs = sorted(struct.unpack_from('<II', d, pd.PointerToRawData + 12 * k) for k in range(pd.Misc_VirtualSize // 12))
    fs = [f for f in fs if f[0]]
    st = [f[0] for f in fs]
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_BASERELOC']])
    rel = sorted(e.rva for b in pe.DIRECTORY_ENTRY_BASERELOC for e in b.entries)
    for m in re.finditer(rb'\xcc{%d,}' % need, code):
        a, b = va + m.start(), va + m.end()
        s = (a + margin + align - 1) & ~(align - 1)     # keep int3 margin before
        if s + need > b - margin: continue                # and after
        if any(s < x + y and x < s + need for x, y in avoid): continue
        j = bisect.bisect_right(st, s + need - 1) - 1
        if j >= 0 and fs[j][1] > s: continue              # overlaps a function
        k = bisect.bisect_left(rel, s - 7)
        if k < len(rel) and rel[k] < s + need: continue
        return s, s - va + raw
    raise SystemExit('no padding')

def gen(name, out):
    path = name + '.dll'
    blob = open(path, 'rb').read()
    pe = pefile.PE(path, fast_load=True); d = pe.__data__
    sha = hashlib.sha256(blob).hexdigest()
    t = pe.sections[0]
    def off(rva): return rva - t.VirtualAddress + t.PointerToRawData
    fpad, fpad_off = pick_pad(pe, d, 8, 4, [])
    dpad, dpad_off = pick_pad(pe, d, 16, 4, [(fpad, 8)], margin=0)
    newc = {'f_64': fpad, 'f_inv': fpad + 4, 'd_64': dpad, 'd_inv': dpad + 8}
    plan = json.load(open(path + '.plan.json'))
    rows = []
    for s in plan:
        if s['act'] != 'patch': continue
        ib = bytes.fromhex(s['bytes']); a = s['addr']; L = len(ib)
        if s['kind'] == 'rip':
            want = struct.pack('<i', s['target'] - (a + L))
            pos = [i for i in range(L - 3) if ib[i:i + 4] == want]
            assert len(pos) == 1, (name, hex(a), s['ops'])
            p = pos[0]
            # the new displacement must account for bytes after the disp (imm8 etc.)
            newdisp = newc[s['const']] - (a + L)
            rows.append((off(a) + p, 0, KIND[s['const']], ib[p:p + 4], newdisp, hex(a), s['mn'] + ' ' + s['ops']))
        else:
            pat = ORIG[s['const']]
            pos = [i for i in range(L - 3) if ib[i:i + 4] == pat]
            assert len(pos) == 1, (name, hex(a), s['ops'])
            rows.append((off(a) + pos[0], 1, KIND[s['const']], pat, 0, hex(a), s['mn'] + ' ' + s['ops']))
    # raw instruction edits (reviewed by hand)
    for rva, new, why in RAW.get(name, []):
        o = off(rva); ob = blob[o:o + 4]
        nb = new + ob[len(new):]
        rows.append((o, 2, 0, ob, struct.unpack('<i', nb)[0], hex(rva), why))
    rows.sort()
    sym = name.upper()
    out.append('/* %s.dll  CS2 1.42.0.1  sha256 %s  size %d */' % (name, sha, len(blob)))
    out.append('static const tp_site %s_SITES[] = {' % sym)
    for o, typ, k, ob, nd, rva, txt in rows:
        out.append('  {0x%08x, %d, %d, {0x%02x,0x%02x,0x%02x,0x%02x}, %d}, /* %s %s */' %
                   (o, typ, k, ob[0], ob[1], ob[2], ob[3], nd, rva, txt.replace('*/', '* /')))
    out.append('};')
    out.append('static const tp_dll %s_DLL = { L"%s", %d, "%s", 0x%08x, 0x%08x, %s_SITES, %d };' %
               (sym, {'engine2': 'game\\\\bin\\\\win64\\\\engine2.dll', 'server': 'game\\\\csgo\\\\bin\\\\win64\\\\server.dll',
                      'client': 'game\\\\csgo\\\\bin\\\\win64\\\\client.dll'}[name],
                len(blob), sha, fpad_off, dpad_off, sym, len(rows)))
    print(name, 'sites', len(rows), 'fpad rva %x dpad rva %x' % (fpad, dpad))
    return len(rows)

if __name__ == '__main__':
    out = ['/* Generated by tools/gen_table.py from CS2 1.42.0.1 (Nov 23 2026). Do not edit. */',
           '#pragma once']
    tot = 0
    for n in ('engine2', 'server', 'client'): tot += gen(n, out)
    out.append('static const tp_dll *const TP_BUILD_1420[3] = { &ENGINE2_DLL, &SERVER_DLL, &CLIENT_DLL };')
    out.append('#define TP_BUILD_1420_NAME "1.42.0.1 (Nov 23 2026)"')
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'engine', 'sites_1420.h'), 'w').write('\n'.join(out) + '\n')
    print('total', tot)
